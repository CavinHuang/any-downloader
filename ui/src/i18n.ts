const lang = navigator.language.toLowerCase().startsWith("zh") ? zh : en;

// <html lang> 随词典语言（A6；index.html 静态值仅作回退）
document.documentElement.lang = lang === zh ? "zh-CN" : "en";

export const t = (key: string): string => lang[key] ?? zh[key] ?? key;

export function errorCodeOf(err: unknown): string | null {
  if (!err) return null;
  if (typeof err === "string") return err;
  if (typeof err === "object") {
    const obj = err as Record<string, unknown>;
    if (typeof obj.code === "string") return obj.code;
    const keys = Object.keys(obj);
    if (keys.length === 1) return keys[0];
  }
  return null;
}

export function formatTaskError(err: unknown): string {
  if (!err) return "";
  if (typeof err === "string") {
    const key = `err_${err}`;
    const mapped = t(key);
    return mapped === key ? err : mapped;
  }
  if (typeof err === "object") {
    const obj = err as Record<string, unknown>;
    if (typeof obj.code === "string") {
      const key = `err_${obj.code}`;
      const mapped = t(key);
      return mapped === key ? obj.code : mapped;
    }
    if ("http" in obj && obj.http && typeof obj.http === "object") {
      const st = (obj.http as { status?: number }).status;
      return st ? `HTTP ${st}` : "HTTP";
    }
    if ("interstitial_page" in obj && obj.interstitial_page && typeof obj.interstitial_page === "object") {
      const title = (obj.interstitial_page as { title?: string | null }).title;
      return title ? `${t("err_interstitial_page")}: ${title}` : t("err_interstitial_page");
    }
    const keys = Object.keys(obj);
    if (keys.length === 1) {
      const key = `err_${keys[0]}`;
      const mapped = t(key);
      return mapped === key ? keys[0] : mapped;
    }
  }
  return String(err);
}
